# ================================================================ settings / helpers
def ai_mode(store: Store, hid: str) -> str:
    h = store.get(f"households/{hid}")
    return (h.data.get("aiMode") if h else None) or "offline"


def ai_status(store: Store, actor: CurrentUser, hid: str) -> dict:
    authorize(store, actor.uid, hid)
    configured = get_llm() is not None
    mode = ai_mode(store, hid)
    return {"mode": mode, "geminiConfigured": configured, "effectiveEngine": "gemini" if mode == "gemini" and configured else "offline",
            "model": get_settings().gemini_model if configured else None}


def set_ai_mode(store: Store, actor: CurrentUser, hid: str, mode: str) -> dict:
    authorize(store, actor.uid, hid, P.HOUSEHOLD_MANAGE)
    if mode not in ("offline", "gemini"):
        raise ValidationFailed("Unknown AI mode.")
    before = ai_mode(store, hid)
    store.update(f"households/{hid}", {"aiMode": mode})
    audit.record(store, hid, actor, "settings.ai", "settings", "ai",
                 "Enabled cloud AI (Gemini) for this household" if mode == "gemini" else "Switched AI to offline mode",
                 {"aiMode": before}, {"aiMode": mode})
    return ai_status(store, actor, hid)


def _llm_for(store: Store, hid: str):
    return get_llm() if ai_mode(store, hid) == "gemini" else None


def _throttle(actor: CurrentUser) -> None:
    if not limiter.allow(f"ai:{actor.uid}", get_settings().ai_rate_limit_per_hour, 3600):
        raise RateLimited("You've reached the hourly limit for AI requests. Please try again later.")


def _log(store: Store, hid: str, actor: CurrentUser, action: str, summary: str, sid: str | None, engine: str) -> None:
    # Audit WHO used WHICH AI workflow — never the question or the content.
    audit.record(store, hid, actor, f"ai.{action}", "ai", action, f"{summary} ({engine})", senior_id=sid)


