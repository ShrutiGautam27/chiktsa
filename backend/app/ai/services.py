"""PHASE 4 — AI workflows.

Every service follows the same contract:
  1. Build the MINIMAL authorised context for one senior in one household (scope + consent aware).
  2. If the household opted in to cloud AI and Gemini is configured, ask the model for a
     schema-validated JSON answer; validate references against the context; apply guardrails.
  3. Otherwise — or if the model fails validation — use a deterministic offline engine.
  4. Label the result with `engine` ("gemini" | "offline") and never write data without a human
     confirming it (prescription drafts and task proposals are proposals only).
"""
