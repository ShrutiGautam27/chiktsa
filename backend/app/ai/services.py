_STOP = set("a an the is was were be been of to in on at for with and or but what when which who how did does do i we he she they it "
            "this that these those my our his her their about from any there have has had last recent please tell me show ka ki ke "
            "hai tha kya kab".split())


def _tokens(text: str) -> list[str]:
    return [t for t in re.findall(r"[a-z0-9ऀ-ॿ]+", (text or "").lower()) if t not in _STOP and len(t) > 1]


def build_corpus(store: Store, acc: Access, sid: str) -> list[dict]:
    hid = acc.hid
    s = acc.senior(sid) or {}
    docs: list[dict] = []

    def add(rtype, rid, date, title, text, link):
        if text and text.strip():
            docs.append({"id": f"{rtype}:{rid}", "type": rtype, "date": date, "title": title, "text": text.strip(), "link": link})

    if acc.allowed(sid, "care_notes"):
        add("profile", sid, s.get("updatedAt"), "Profile notes", s.get("notes", ""), f"/app/households/{hid}/profiles/{sid}")
        for d in store.query(f"households/{hid}/seniors/{sid}/careNotes"):
            add("note", d.id, d.data["createdAt"], f"Observation by {d.data.get('authorName')}", d.data["text"],
                f"/app/households/{hid}/profiles/{sid}")
    if acc.allowed(sid, "appointments"):
        for d in store.query(f"households/{hid}/seniors/{sid}/appointments"):
            a = d.data
            parts = [f"{a['title']} with {a.get('providerName') or 'provider'} at {a.get('location') or 'unspecified location'}",
                     f"status {a['status']}", f"escort {a.get('escortName') or 'none'}"]
            if a.get("visitNotes"):
                parts.append(f"Visit notes: {a['visitNotes']}")
            if a.get("questions"):
                parts.append("Questions: " + "; ".join(a["questions"]))
            for h in a.get("history") or []:
                parts.append(f"Postponed ({h.get('reason') or 'no reason given'})")
            add("appointment", d.id, a["startsAt"], a["title"], ". ".join(parts), "/app/appointments")
    if acc.allowed(sid, "medications"):
        names = {m["uid"]: m["displayName"] for m in active_members(store, hid)}
        for d in store.query(f"households/{hid}/seniors/{sid}/medications"):
            m = d.data
            v = m.get("verification") or {}
            parts = [f"{m.get('name') or 'Unclear name'} {m.get('strength', '')}".strip()
                     + f": {m.get('doseQuantity')} {m.get('doseUnit')} at {', '.join(m.get('times') or []) or 'no set times'}",
                     m.get("instructions") or "", f"status {m['status'].replace('_', ' ')}",
                     f"verified by {v.get('verifiedByName')}" if v else "not verified",
                     f"doses confirmed by {names.get(m.get('responsibleUid'), 'nobody assigned')}",
                     f"prescriber {m.get('prescriber') or 'not recorded'}"]
            txt = "; ".join(p for p in parts if p)
            add("medication", d.id, m.get("updatedAt") or m["createdAt"], m.get("name") or "Medication", txt, "/app/medications")
    if acc.allowed(sid, "documents"):
        for d in store.query(f"households/{hid}/seniors/{sid}/documents"):
            x = d.data
            if x.get("status") == "active":
                add("document", d.id, x.get("documentDate") or x["createdAt"], x["title"],
                    f"{x['kind'].replace('_', ' ')}: {x['title']}. {x.get('extractedText') or ''}", "/app/documents")
    if acc.can(P.HANDOVER_WRITE):
        for d in store.query(f"households/{hid}/handovers"):
            h = d.data
            if sid in h["seniorIds"] and all(acc.can_see(x) for x in h["seniorIds"]):
                add("handover", d.id, h["createdAt"], f"Handover {h['fromName']} → {h['toName']}",
                    " ".join([h.get("observations", ""), *h.get("instructions", []), h.get("scheduleChanges", "")]), "/app/handover")
    for d in store.query(f"households/{hid}/tasks"):
        t = d.data
        if t.get("seniorId") == sid and t["status"] == "done" and not (t.get("kind") == "medication_check" and not acc.allowed(sid, "medications")):
            add("task", d.id, t.get("completedAt"), t["title"], f"{t['title']} completed by {t.get('completedByName')}. {t.get('completionNote') or ''}",
                "/app/tasks")
    return docs


def retrieve(corpus: list[dict], question: str, k: int = 6) -> list[dict]:
    q = _tokens(question)
    if not q or not corpus:
        return []
    toks = [Counter(_tokens(d["title"] + " " + d["text"])) for d in corpus]
    n = len(corpus)
    df = Counter(t for c in toks for t in set(c))
    scored = []
    for d, c in zip(corpus, toks):
        length = sum(c.values()) or 1
        score = sum((c[t] / length) * math.log(1 + n / df[t]) for t in q if c[t])
        if score > 0:
            scored.append((score, d))
    scored.sort(key=lambda x: -x[0])
    return [d for _, d in scored[:k]]


class MemoryAnswer(BaseModel):
    answer: str
    citations: list[str] = Field(default_factory=list)
    insufficient: bool = False
    clinicalEscalation: bool = False


def _cite(d: dict) -> dict:
    return {"id": d["id"], "type": d["type"], "title": d["title"], "date": d["date"], "link": d["link"],
            "snippet": d["text"][:220] + ("…" if len(d["text"]) > 220 else "")}


def ask_memory(store: Store, actor: CurrentUser, hid: str, sid: str, question: str) -> dict:
    question = (question or "").strip()
    if not 3 <= len(question) <= 500:
        raise ValidationFailed("Ask a question between 3 and 500 characters.")
    acc = Access(store, actor.uid, hid, P.SENIOR_READ)
    senior = acc.require(sid)
    _throttle(actor)
    hits = retrieve(build_corpus(store, acc, sid), question)
    clinical = is_clinical_question(question)
    llm = _llm_for(store, hid)
    engine = "offline"
    result: MemoryAnswer | None = None
    if llm and hits:
        ctx = "\n".join(f"[{d['id']}] ({str(d['date'])[:10]}, {d['type']}) {d['title']}: {d['text']}" for d in hits)
        try:
            out = llm.generate(SYSTEM_RULES, f"Person: {senior['fullName']}\nRecords:\n{ctx}\n\nQuestion: {question}\n"
                                             "Answer from the records only and cite record IDs exactly as given.", MemoryAnswer)
            valid = [c for c in out.citations if c in {d["id"] for d in hits}]
            text, blocked = sanitize(out.answer)
            if blocked or out.clinicalEscalation or clinical:
                result = MemoryAnswer(answer=CLINICAL_ESCALATION, citations=valid, clinicalEscalation=True)
            elif out.insufficient or not valid:
                result = MemoryAnswer(answer="I couldn't find this in the care records you have access to.", insufficient=True)
            else:
                result = MemoryAnswer(answer=text, citations=valid)
            engine = "gemini"
        except AIUnavailable:
            result = None
    if result is None:
        if clinical:
            result = MemoryAnswer(answer=CLINICAL_ESCALATION, citations=[d["id"] for d in hits[:3]], clinicalEscalation=True)
        elif not hits:
            result = MemoryAnswer(answer="I couldn't find anything about that in the care records you have access to.", insufficient=True)
        else:
            top = hits[:3]
            lines = [f"• {str(d['date'])[:10]} — {d['title']}: {d['text'][:180]}{'…' if len(d['text']) > 180 else ''}" for d in top]
            result = MemoryAnswer(answer="Here's what the records say:\n" + "\n".join(lines), citations=[d["id"] for d in top])
    by_id = {d["id"]: d for d in hits}
    _log(store, hid, actor, "memory_query", "Asked the Care Memory Bridge", sid, engine)
    return {"answer": result.answer, "citations": [_cite(by_id[c]) for c in result.citations if c in by_id],
            "insufficient": result.insufficient, "clinicalEscalation": result.clinicalEscalation, "engine": engine,
            "note": OFFLINE_NOTE if engine == "offline" else "Generated by Gemini from the cited records only.",
            "recordsSearched": len(hits)}


# ================================================================ Daily Care Briefing
class BriefingPriority(BaseModel):
    text: str
    factId: str


class BriefingOut(BaseModel):
    headline: str
    summary: str
    priorities: list[BriefingPriority] = Field(default_factory=list, max_length=6)


def _briefing_facts(store: Store, actor: CurrentUser, acc: Access) -> list[dict]:
    hid, t = acc.hid, now()
    facts: list[dict] = []
    gaps = detect_gaps(store, actor, hid)["gaps"]
    for g in gaps[:5]:
        facts.append({"id": f"gap:{g['id']}", "text": f"{g['title']}: {g['detail']}", "priority": g["severity"], "link": g["link"]})
    for sid in acc.visible_senior_ids():
        s = acc.senior(sid)
        if acc.allowed(sid, "medications") and acc.can(P.SENIOR_MEDICAL_READ):
            tz = s.get("timezone") or "UTC"  # type: ignore[union-attr]
            ev = meds._schedule(store, hid, sid, tz, local_date(t, tz), local_date(t, tz))
            if ev:
                c = Counter(e["status"] for e in ev)
                facts.append({"id": f"doses:{sid}", "priority": "low", "link": "/app/medications",
                              "text": f"{s['fullName']}: {len(ev)} dose(s) scheduled today — {c.get('taken', 0)} recorded taken, "  # type: ignore[index]
                                      f"{c.get('skipped', 0)} skipped, {c.get('unconfirmed', 0)} not yet recorded, {c.get('scheduled', 0)} upcoming."})
        if acc.allowed(sid, "appointments") and acc.can(P.SENIOR_MEDICAL_READ):
            for d in store.query(f"households/{hid}/seniors/{sid}/appointments"):
                a = d.data
                st = aware(a["startsAt"])
                if a["status"] == "scheduled" and t <= st <= t + timedelta(hours=48):
                    facts.append({"id": f"appointment:{d.id}", "priority": "medium", "link": "/app/appointments",
                                  "text": f"{s['fullName']}: '{a['title']}' on {st.astimezone(ZoneInfo(s.get('timezone') or 'UTC')):%a %d %b, %H:%M}"  # type: ignore[index]
                                          f" — {('with ' + a['escortName']) if a.get('escortName') else 'nobody accompanying yet'}."})
    resp = coordination.responsibilities(store, actor)
    mine = [x for x in resp["myTasks"] if x["householdId"] == hid]
    if mine:
        facts.append({"id": "mytasks", "priority": "medium", "link": "/app/tasks", "text": f"You have {len(mine)} open task(s): "
                      + "; ".join(x["title"] for x in mine[:4]) + ("…" if len(mine) > 4 else "") + "."})
    ho = [x for x in resp["handoversToAcknowledge"] if x["householdId"] == hid]
    if ho:
        facts.append({"id": "handovers", "priority": "high", "link": "/app/handover",
                      "text": f"{len(ho)} handover(s) are waiting for your acknowledgement."})
    return facts


def daily_briefing(store: Store, actor: CurrentUser, hid: str, refresh: bool = False) -> dict:
    acc = Access(store, actor.uid, hid, P.TASKS_READ)
    tz = (store.get(f"households/{hid}").data.get("timezone")) or "UTC"
    day = local_date(now(), tz).isoformat()
    cache_path = f"households/{hid}/briefings/{actor.uid}_{day}"
    cached = store.get(cache_path)
    if cached and not refresh and now() - aware(cached.data["generatedAt"]) < timedelta(minutes=30):
        return cached.data["result"]
    _throttle(actor)
    facts = _briefing_facts(store, actor, acc)
    order = {"high": 0, "medium": 1, "low": 2}
    facts.sort(key=lambda f: order[f["priority"]])
    engine, out = "offline", None
    llm = _llm_for(store, hid)
    if llm and facts:
        try:
            fact_txt = "\n".join(f"[{f['id']}] ({f['priority']}) {f['text']}" for f in facts)
            res = llm.generate(SYSTEM_RULES, f"Write today's care briefing for {actor.display_name} from these verified facts only:\n"
                                             f"{fact_txt}\nReturn a short headline, a 2-3 sentence summary and up to 5 priorities "
                                             "each referencing one fact id.", BriefingOut)
            ids = {f["id"] for f in facts}
            pri = [p for p in res.priorities if p.factId in ids and not contains_unsafe_advice(p.text)]
            summary, blocked = sanitize(res.summary)
            if not blocked:
                out = {"headline": res.headline[:140], "summary": summary,
                       "priorities": [{"text": p.text, "factId": p.factId, "link": next(f["link"] for f in facts if f["id"] == p.factId)} for p in pri]}
                engine = "gemini"
        except AIUnavailable:
            out = None
    if out is None:
        urgent = [f for f in facts if f["priority"] == "high"]
        out = {"headline": (f"{len(urgent)} thing{'s' if len(urgent) != 1 else ''} need attention today" if urgent
                            else "Everything important has an owner today" if facts else "A quiet day — nothing scheduled"),
               "summary": " ".join(f["text"] for f in facts[:2]) or "No appointments, doses or open responsibilities need you right now.",
               "priorities": [{"text": f["text"], "factId": f["id"], "link": f["link"]} for f in facts[:5]]}
    result = {**out, "engine": engine, "date": day, "generatedAt": now(), "factsUsed": len(facts),
              "note": OFFLINE_NOTE if engine == "offline" else "Written by Gemini from verified records only."}
    store.set(cache_path, {"generatedAt": now(), "result": result})
    _log(store, hid, actor, "briefing", "Generated the daily care briefing", None, engine)
    return result


# ================================================================ Appointment preparation
class PrepOut(BaseModel):
    summary: str
    suggestedQuestions: list[str] = Field(default_factory=list, max_length=8)


def appointment_prep(store: Store, actor: CurrentUser, hid: str, sid: str, aid: str) -> dict:
    acc = Access(store, actor.uid, hid)
    s = acc.require(sid, P.SENIOR_MEDICAL_READ, "appointments")
    a = store.get(f"households/{hid}/seniors/{sid}/appointments/{aid}")
    if not a:
        raise NotFound("Appointment not found.")
    _throttle(actor)
    x, tz, t = a.data, s.get("timezone") or "UTC", now()
    sections: dict[str, list] = {"medications": [], "unverified": [], "adherence": [], "observations": [], "previousVisits": [],
                                 "documents": []}
    questions = list(x.get("questions") or [])
    generated: list[str] = []
    if acc.allowed(sid, "medications"):
        ad = meds.adherence(store, actor, hid, sid, 14)
        for d in store.query(f"households/{hid}/seniors/{sid}/medications"):
            m = d.data
            if m["status"] == "active":
                sections["medications"].append({"name": m["name"], "strength": m.get("strength"), "dose": f"{m.get('doseQuantity')} {m.get('doseUnit')}",
                                                "times": m.get("times"), "instructions": m.get("instructions"),
                                                "verifiedBy": (m.get("verification") or {}).get("verifiedByName")})
                rf = meds.refill_status(m, local_date(t, tz))
                if rf.get("tracked") and rf["level"] != "ok":
                    generated.append(f"Ask for a repeat prescription for {m['name']} — recorded stock lasts about {rf['daysRemaining']} day(s).")
            elif m["status"] == "pending_verification":
                issues = [i for i in meds.analyse(m, []) if i["severity"] == "blocking"]
                sections["unverified"].append({"name": m.get("name") or "Unclear medicine", "issues": [i["message"] for i in issues]})
                generated.append(f"Ask the doctor to confirm the details of {m.get('name') or 'the unclear medicine on the prescription'} "
                                 "— it couldn't be verified yet.")
        sections["adherence"] = [{"name": r["name"], **{k: r[k] for k in ("taken", "skipped", "unconfirmed")}} for r in ad["byMedication"]]
    if acc.allowed(sid, "care_notes"):
        since = t - timedelta(days=30)
        notes = [d.data for d in store.query(f"households/{hid}/seniors/{sid}/careNotes") if aware(d.data["createdAt"]) >= since]
        sections["observations"] = [{"date": n["createdAt"], "text": n["text"], "by": n.get("authorName")}
                                    for n in sorted(notes, key=lambda n: n["createdAt"], reverse=True)[:10]]
    prev = [d.data for d in store.query(f"households/{hid}/seniors/{sid}/appointments") if d.data["status"] == "completed" and d.id != aid]
    sections["previousVisits"] = [{"title": p["title"], "date": p["startsAt"], "notes": p.get("visitNotes")}
                                  for p in sorted(prev, key=lambda p: p["startsAt"], reverse=True)[:3]]
    if acc.allowed(sid, "documents"):
        sections["documents"] = [{"title": d.data["title"], "kind": d.data["kind"], "date": d.data.get("documentDate") or d.data["createdAt"]}
                                 for d in store.query(f"households/{hid}/seniors/{sid}/documents") if d.data.get("status") == "active"]
    bring = ["This preparation sheet (print or show on your phone)", "All current medicine strips or bottles"]
    if sections["documents"]:
        bring.append("Recent reports: " + ", ".join(d["title"] for d in sections["documents"][:3]))
    engine, summary = "offline", (f"{s['fullName']} is seeing {x.get('providerName') or 'the doctor'} for '{x['title']}'. "
                                  f"{len(sections['medications'])} verified active medicine(s) and {len(sections['observations'])} recent "
                                  f"observation(s) are listed below. Nothing here is a diagnosis — it's a record to share with the doctor.")
    llm = _llm_for(store, hid)
    if llm:
        try:
            ctx = {"appointment": {"title": x["title"], "provider": x.get("providerName")}, **sections}
            res = llm.generate(SYSTEM_RULES, f"Prepare a doctor-visit summary for {s['fullName']} from this record JSON:\n{ctx}\n"
                                             "Write a factual 3-4 sentence summary for the doctor and up to 5 neutral questions the "
                                             "family could ask. Questions must not suggest diagnoses or medication changes.", PrepOut)
            text, blocked = sanitize(res.summary)
            if not blocked:
                summary = text
                generated += [q for q in res.suggestedQuestions if not contains_unsafe_advice(q)][:5]
                engine = "gemini"
        except AIUnavailable:
            pass
    _log(store, hid, actor, "appointment_prep", f"Prepared a visit summary for '{x['title']}'", sid, engine)
    return {"appointment": {"id": aid, "title": x["title"], "providerName": x.get("providerName"), "location": x.get("location"),
                            "startsAt": x["startsAt"], "seniorName": s["fullName"]},
            "summary": summary, "sections": sections, "familyQuestions": questions, "suggestedQuestions": list(dict.fromkeys(generated)),
            "bring": bring, "engine": engine,
            "note": OFFLINE_NOTE if engine == "offline" else "Summary and suggested questions written by Gemini from the records shown."}


# ================================================================ Prescription extraction
class RxItem(BaseModel):
    name: str = ""
    strength: str = ""
    form: str = "tablet"
    doseQuantity: float | None = None
    doseUnit: str = "tablet"
    frequencyText: str = ""
    durationText: str = ""
    instructions: str = ""
    sourceText: str = ""
    uncertainFields: list[str] = Field(default_factory=list)


class RxOut(BaseModel):
    prescriber: str = ""
    prescriptionDate: str = ""
    medications: list[RxItem] = Field(default_factory=list, max_length=20)
    legibilityNotes: str = ""
    transcription: str = ""


_FORMS = {"tab": "tablet", "tablet": "tablet", "cap": "capsule", "capsule": "capsule", "syp": "liquid", "syrup": "liquid",
          "inj": "injection", "drops": "drops", "drop": "drops", "inh": "inhaler"}
_RX_FREQ = r"(\b(?:od|bd|bid|tds|tid|qid|qds|hs|sos|prn|once daily|twice daily|thrice daily|daily|at night|at bedtime)\b|\b[0-9½?]-[0-9½?]-[0-9½?]\b)"
_RX_STRENGTH = r"(\d+(?:\.\d+)?\s?(?:mg|mcg|µg|g|ml|iu|units?)\b|\?\s?(?:mg|mcg|g|ml))"
_RX_DUR = r"((?:x|for)\s*\d+\s*(?:days?|weeks?|months?))"
_RX_INSTR = r"((?:before|after|with)\s+(?:food|meals?|breakfast|lunch|dinner)|empty stomach)"
VALID_UNCERTAIN = {"name", "strength", "doseQuantity", "frequencyText", "instructions", "doseUnit"}


def parse_prescription_text(text: str) -> RxOut:
    """Offline parser for a TRANSCRIBED prescription. Anything it can't read stays empty (never guessed);
    fields containing '?' (unreadable for the transcriber) are flagged uncertain."""
    items: list[RxItem] = []
    prescriber = ""
    for raw in (text or "").splitlines():
        line = raw.strip(" -•\t")
        if not line:
            continue
        mdr = re.match(r"(?i)^(dr\.?|doctor)\s+(.+)$", line)
        if mdr:
            prescriber = line
            continue
        low = line.lower()
        form_m = re.match(r"(?i)^(tab|tablet|cap|capsule|syp|syrup|inj|drops?|inh)\.?\s+", line)
        st = re.search(_RX_STRENGTH, line, re.I)
        fq = re.search(_RX_FREQ, low)
        if not (form_m or st or fq):
            continue
        rest = line[form_m.end():] if form_m else line
        name = re.split(r"\s(?=\d|\?|od\b|bd\b|tds\b|qid\b|hs\b|[0-9?]-)", rest, maxsplit=1, flags=re.I)[0].strip(" ,")
        item = RxItem(name=name.replace("?", "").strip(), strength=(st.group(1) if st else "").replace(" ", " "),
                      form=_FORMS.get(form_m.group(1).lower().rstrip("."), "tablet") if form_m else "tablet",
                      frequencyText=fq.group(1) if fq else "", sourceText=line)
        if fq and re.match(r"[0-9½?]-", fq.group(1)):
            first = [p for p in fq.group(1).split("-") if p not in ("0",)]
            item.doseQuantity = None if "?" in fq.group(1) else (1.0 if first else None)
            if "?" in fq.group(1):
                item.uncertainFields.append("doseQuantity")
        else:
            item.doseQuantity = 1.0 if form_m and form_m.group(1).lower().startswith(("tab", "cap")) else None
        dur = re.search(_RX_DUR, low)
        ins = re.search(_RX_INSTR, low)
        item.durationText = dur.group(1) if dur else ""
        item.instructions = ins.group(1) if ins else ""
        item.doseUnit = item.form if item.form in ("tablet", "capsule") else ("ml" if item.form == "liquid" else item.form)
        if "?" in name:
            item.uncertainFields.append("name")
        if st and "?" in st.group(1):
            item.uncertainFields.append("strength")
            item.strength = ""
        if "?" in line and not item.uncertainFields:
            item.uncertainFields += ["doseQuantity", "frequencyText"]
        items.append(item)
    return RxOut(prescriber=prescriber, medications=items, transcription=text,
                 legibilityNotes="Parsed from a manual transcription by Chiktsa's offline rules.")


def extract_prescription(store: Store, actor: CurrentUser, hid: str, sid: str, did: str, transcription: str | None) -> dict:
    acc = Access(store, actor.uid, hid)
    acc.require(sid, P.SENIOR_MEDICAL_WRITE, "documents")
    d = get_doc(store, actor, hid, sid, did)
    if d.data["kind"] != "prescription":
        raise ValidationFailed("Only prescription documents can be extracted.")
    _throttle(actor)
    llm, engine, rx = _llm_for(store, hid), "offline", None
    if llm:
        try:
            data = get_storage().get(d.data["storageKey"])
            res = llm.generate(SYSTEM_RULES + "\nYou are transcribing a prescription image. Copy ONLY what is written. "
                               "If any field is hard to read, leave it empty and list it in uncertainFields. Do not infer dose "
                               "times from frequency abbreviations.", "Extract every medicine on this prescription." +
                               (f"\nThe family also transcribed: {transcription}" if transcription else ""), RxOut,
                               files=[(d.data["contentType"], data)])
            for it in res.medications:
                it.uncertainFields = [f for f in it.uncertainFields if f in VALID_UNCERTAIN]
            rx, engine = res, "gemini"
        except AIUnavailable:
            rx = None
    if rx is None:
        if not (transcription or "").strip():
            out = {"status": "needs_transcription", "engine": "offline", "medications": [],
                   "message": "Reading handwriting from a photo needs the Gemini integration. Please type what the prescription "
                              "says (one medicine per line) and Chiktsa will structure it."}
            store.update(d.path, {"extraction": {**out, "at": now()}})
            return out
        rx = parse_prescription_text(transcription or "")
    out = {"status": "extracted", "engine": engine, "prescriber": rx.prescriber, "prescriptionDate": rx.prescriptionDate,
           "medications": [m.model_dump() for m in rx.medications], "legibilityNotes": rx.legibilityNotes,
           "message": "Review every field against the original. Nothing becomes a schedule until it is verified."}
    store.update(d.path, {"extraction": {**out, "at": now()}, "extractedText": rx.transcription or transcription or ""})
    _log(store, hid, actor, "prescription_extract", f"Extracted {len(rx.medications)} medicine(s) from a prescription", sid, engine)
    return out


def create_drafts(store: Store, actor: CurrentUser, hid: str, sid: str, did: str, indexes: list[int],
                  responsible_uid: str | None) -> list[dict]:
    """Turn reviewed extraction items into PENDING medications. Times are never guessed — the Confusion
    Firewall then requires a human to set and verify them."""
    d = get_doc(store, actor, hid, sid, did)
    ext = d.data.get("extraction") or {}
    items = ext.get("medications") or []
    if not items or ext.get("status") != "extracted":
        raise ValidationFailed("Extract the prescription first.")
    if not indexes or any(i < 0 or i >= len(items) for i in indexes):
        raise ValidationFailed("Choose which extracted medicines to add.")
    created = []
    for i in dict.fromkeys(indexes):
        it = items[i]
        payload = {"name": it.get("name") or "", "strength": it.get("strength") or "", "form": it.get("form") or "tablet",
                   "doseQuantity": it.get("doseQuantity"), "doseUnit": it.get("doseUnit") or "tablet",
                   "route": "oral", "frequencyText": it.get("frequencyText") or "", "times": [], "daysOfWeek": list(range(7)),
                   "startDate": None, "endDate": None, "instructions": " ".join(x for x in (it.get("instructions"), it.get("durationText")) if x),
                   "prescriber": ext.get("prescriber") or "", "source": "prescription",
                   "prescriptionText": it.get("sourceText") or "", "uncertainFields": [f for f in it.get("uncertainFields", []) if f in VALID_UNCERTAIN],
                   "stockQuantity": None, "lowStockDays": 7, "responsibleUid": responsible_uid, "pharmacy": ""}
        if not payload["name"] and "name" not in payload["uncertainFields"]:
            payload["uncertainFields"].append("name")
        created.append(meds.create(store, actor, hid, sid, payload))
    return created


# ================================================================ Dialect-to-Care Task Converter
class TaskProposalOut(BaseModel):
    title: str
    seniorId: str | None = None
    assigneeUid: str | None = None
    dueAt: str | None = None
    kind: str = "general"
    needsClarification: bool = False
    clarification: str = ""


class TaskProposals(BaseModel):
    tasks: list[TaskProposalOut] = Field(default_factory=list, max_length=8)


_KINDS = [
    ("errand", r"\b(refill|pharmacy|chemist|buy|purchase|grocer|sabzi|market|pick ?up|collect|lana|le aana|kharid)"),
    ("appointment_escort", r"\b(doctor|hospital|clinic|appointment|checkup|check-up|visit|dikhana)"),
    ("medication_check", r"\b(medicine|medication|tablet|pill|dawai|dawa|dose)"),
    ("follow_up", r"\b(call|phone|follow ?up|report|result|baat)"),
    ("household", r"\b(clean|repair|bill|electric|plumber|safai)"),
]
_DAYS = {"monday": 0, "tuesday": 1, "wednesday": 2, "thursday": 3, "friday": 4, "saturday": 5, "sunday": 6,
         "somvar": 0, "mangalvar": 1, "budhvar": 2, "guruvar": 3, "shukravar": 4, "shanivar": 5, "ravivar": 6}


def _offline_tasks(text: str, seniors: list[dict], members: list[dict], tz: str, t: datetime) -> list[TaskProposalOut]:
    clauses = [c.strip() for c in re.split(r"[.;\n]+|\b(?:and then|aur phir|then)\b", text, flags=re.I) if len(c.strip()) > 3]
    local_now = t.astimezone(ZoneInfo(tz))
    out = []
    for c in clauses[:8]:
        low = c.lower()
        notes = []
        sid = None
        for s in seniors:
            names = {s["fullName"].lower(), s["fullName"].split()[0].lower()} | ({s["preferredName"].lower()} if s.get("preferredName") else set())
            if any(re.search(rf"\b{re.escape(n)}\b", low) for n in names if n):
                sid = s["id"]
                break
        uid = None
        future = r"\b(jayegi|jayega|jaayegi|jaayega|karegi|karega|legi|lega|degi|dega|layegi|layega|will)\b"
        for m in members:
            first = m["displayName"].split()[0].lower()
            if re.search(rf"\b(ask|tell|remind|by)\s+{re.escape(first)}\b|\b{re.escape(first)}\s+(ko|to|will|should|can)\b", low) or \
                    (re.search(rf"\b{re.escape(first)}\b", low) and re.search(future, low)):  # "Priya ... le jayegi"
                uid = m["uid"]
                break
        day = None
        if re.search(r"\b(today|aaj|tonight)\b", low):
            day = local_now.date()
        elif re.search(r"\b(tomorrow|kal)\b", low):
            day = local_now.date() + timedelta(days=1)
            if re.search(r"\bkal\b", low):
                notes.append("“Kal” can mean yesterday or tomorrow — assumed tomorrow.")
        else:
            for name, wd in _DAYS.items():
                if re.search(rf"\b{name}\b", low):
                    day = local_now.date() + timedelta(days=(wd - local_now.weekday()) % 7 or 7)
                    break
        hh = None
        tm = re.search(r"\b(?:at\s*)?(\d{1,2})(?::(\d{2}))?\s*(am|pm|baje)\b", low)
        if tm:
            h = int(tm.group(1)) % 12 + (12 if tm.group(3) == "pm" else 0)
            if tm.group(3) == "baje" and int(tm.group(1)) < 8:
                h = int(tm.group(1)) + 12
                notes.append("Assumed afternoon/evening for the time given.")
            hh = (h, int(tm.group(2) or 0))
        due = None
        if day or hh:
            day = day or local_now.date()
            h, mi = hh or (18, 0)
            if not hh:
                notes.append("No time given — set to 6 pm.")
            due = datetime(day.year, day.month, day.day, h, mi, tzinfo=ZoneInfo(tz)).astimezone(timezone.utc)
            if due <= t:
                notes.append("That time has already passed — please choose a new one.")
                due = None
        kind = next((k for k, pat in _KINDS if re.search(pat, low)), "general")
        title = re.sub(r"\s+", " ", c).strip().rstrip("!")
        title = title[0].upper() + title[1:]
        out.append(TaskProposalOut(title=title[:160], seniorId=sid, assigneeUid=uid, dueAt=due.isoformat() if due else None,
                                   kind=kind, needsClarification=bool(notes), clarification=" ".join(notes)))
    return out


def convert_tasks(store: Store, actor: CurrentUser, hid: str, text: str) -> dict:
    text = (text or "").strip()
    if not 3 <= len(text) <= 1000:
        raise ValidationFailed("Describe the tasks in 3 to 1000 characters.")
    acc = Access(store, actor.uid, hid, P.TASKS_MANAGE)
    _throttle(actor)
    tz = store.get(f"households/{hid}").data.get("timezone") or "UTC"
    t = now()
    seniors = [{"id": sid, "fullName": acc.senior(sid)["fullName"], "preferredName": acc.senior(sid).get("preferredName", "")}  # type: ignore[index]
               for sid in acc.visible_senior_ids()]
    members = [m for m in active_members(store, hid) if m["role"] != "senior"]
    llm, engine, props = _llm_for(store, hid), "offline", None
    if llm:
        try:
            ctx = (f"Now: {t.astimezone(ZoneInfo(tz)).isoformat()} ({tz})\nElderly profiles: "
                   + "; ".join(f"{s['id']} = {s['fullName']} ({s['preferredName']})" for s in seniors)
                   + "\nMembers: " + "; ".join(f"{m['uid']} = {m['displayName']}" for m in members))
            res = llm.generate(SYSTEM_RULES + "\nConvert the family's request (English, Hindi or Hinglish) into care tasks. Use only "
                               "the IDs listed. Use ISO-8601 with offset for dueAt. If anything is ambiguous set needsClarification.",
                               f"{ctx}\nRequest: {text}", TaskProposals)
            props, engine = res.tasks, "gemini"
        except AIUnavailable:
            props = None
    if props is None:
        props = _offline_tasks(text, seniors, members, tz, t)
    sids, uids = {s["id"] for s in seniors}, {m["uid"]: m for m in members}
    proposals = []
    for p in props:
        notes = [p.clarification] if p.clarification else []
        sid = p.seniorId if p.seniorId in sids else None
        uid = p.assigneeUid if p.assigneeUid in uids else None
        if uid and sid and not member_can_see(store, hid, uids[uid], sid):
            notes.append(f"{uids[uid]['displayName']} can't access this profile — choose someone else.")
            uid = None
        due = None
        if p.dueAt:
            try:
                d = aware(datetime.fromisoformat(p.dueAt))
                due = d if d and d > t else None
            except ValueError:
                due = None
        kind = p.kind if p.kind in {k for k, _ in _KINDS} | {"general"} else "general"
        if contains_unsafe_advice(p.title):
            notes.append("Medication changes must come from a doctor; this was not turned into a task.")
            continue
        proposals.append({"title": p.title[:160], "seniorId": sid, "seniorName": next((s["fullName"] for s in seniors if s["id"] == sid), None),
                          "assigneeUid": uid, "assigneeName": uids[uid]["displayName"] if uid else None,
                          "dueAt": due, "kind": kind, "needsClarification": bool(notes) or p.needsClarification,
                          "clarification": " ".join(n for n in notes if n)})
    _log(store, hid, actor, "task_convert", f"Converted a request into {len(proposals)} proposed task(s)", None, engine)
    return {"proposals": proposals, "engine": engine,
            "note": "Proposals only — nothing is saved until you confirm each task."
                    + ("" if engine == "gemini" else " " + OFFLINE_NOTE)}
